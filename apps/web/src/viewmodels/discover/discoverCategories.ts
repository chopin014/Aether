const WORD_SETS = Object.fromEntries(
    Object.entries(CATEGORY_WORDS).map(([category, words]) => [category, new Set(words)]),
) as Record<Exclude<DiscoverCategory, "home">, Set<string>>;

/** Split into lower-case words, keeping inner hyphens and ampersands so "off-topic" and "d&d" survive. */
function words(text: string): string[] {
    return text.toLocaleLowerCase().match(/[\p{L}\p{N}]+(?:[-&][\p{L}\p{N}]+)*/gu) ?? [];
}

/**
 * Whether a community belongs in a Discover category, judged by its name and topic.
 * @param category - The category tab. `home` matches everything.
 * @param name - The community name.
 * @param topic - The community topic, if any.
 */
export function matchesCategory(category: DiscoverCategory, name: string, topic?: string): boolean {
    if (category === "home") return true;
    const wanted = WORD_SETS[category];
    return words(`${name} ${topic ?? ""}`).some((word) => wanted.has(word));
}
